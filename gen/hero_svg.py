# Builds Poppins ExtraBold outlines for the hero headline and cuts a Gilgongo-style
# zigzag strip into the first stroke of every letter. Writes src/components/heroTitleData.js
import json
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.basePen import BasePen

FONT='node_modules/@fontsource/poppins/files/poppins-latin-800-normal.woff'
f=TTFont(FONT); gs=f.getGlyphSet(); cmap=f.getBestCmap(); hmtx=f['hmtx']; upem=f['head'].unitsPerEm
TRACK=-30  # letter-spacing (-0.03em)

class FlatPen(BasePen):
    def __init__(s,gs): super().__init__(gs); s.polys=[]; s.cur=[]
    def _moveTo(s,p): s.cur=[p]
    def _lineTo(s,p): s.cur.append(p)
    def _curveToOne(s,p1,p2,p3):
        p0=s.cur[-1]
        for i in range(1,13):
            t=i/12; mt=1-t
            s.cur.append((mt**3*p0[0]+3*mt*mt*t*p1[0]+3*mt*t*t*p2[0]+t**3*p3[0], mt**3*p0[1]+3*mt*mt*t*p1[1]+3*mt*t*t*p2[1]+t**3*p3[1]))
    def _qCurveToOne(s,p1,p2):
        p0=s.cur[-1]
        for i in range(1,9):
            t=i/8; mt=1-t
            s.cur.append((mt*mt*p0[0]+2*mt*t*p1[0]+t*t*p2[0], mt*mt*p0[1]+2*mt*t*p1[1]+t*t*p2[1]))
    def _closePath(s):
        if len(s.cur)>2: s.polys.append(s.cur)
        s.cur=[]
    _endPath=_closePath

def intervals(polys,y):
    xs=[]
    for poly in polys:
        n=len(poly)
        for i in range(n):
            (x1,y1),(x2,y2)=poly[i],poly[(i+1)%n]
            if (y1<=y<y2) or (y2<=y<y1):
                xs.append(x1+(y-y1)*(x2-x1)/(y2-y1))
    xs.sort()
    return [(xs[i],xs[i+1]) for i in range(0,len(xs)-1,2)]

def zigzag(polys):
    ys=[p[1] for poly in polys for p in poly]
    lo,hi=min(ys),max(ys)
    step=8
    rows=[]
    y=lo+step
    while y<hi-step:
        iv=intervals(polys,y)
        rows.append((y,iv[0] if iv else None))
        y+=step
    # stroke width reference = median width of the first stroke
    ws=sorted(iv[1]-iv[0] for y,iv in rows if iv)
    if not ws: return None
    ref=ws[len(ws)//2]
    # longest continuous run where the first stroke exists, is stroke-like (not a
    # horizontal bar) and doesn't jump sideways
    runs=[];cur=[]
    for y,iv in rows:
        if iv and iv[1]-iv[0] > 1.45*ref:      # crossing a bar: keep only the stroke part
            iv=(iv[0], iv[0]+ref)
        ok = iv and iv[1]-iv[0] > 70 and (not cur or abs(iv[0]-cur[-1][1][0]) < 22)
        if ok: cur.append((y,iv))
        else:
            if cur: runs.append(cur)
            cur=[(y,iv)] if (iv and iv[1]-iv[0] > 70) else []
    if cur: runs.append(cur)
    if not runs: return None
    run=max(runs,key=len)
    if len(run)<16: return None
    m=int(len(run)*0.1); run=run[m:len(run)-m]
    # left edge (smooth) top->bottom, right edge sawtooth bottom->top
    left=[]; right=[]
    TOOTH=120
    for k,(y,(x0,x1)) in enumerate(run):
        w=x1-x0
        left.append((x0+0.18*w,y))
    yb=run[0][0]; yt=run[-1][0]
    t=0
    for k,(y,(x0,x1)) in enumerate(run):
        w=x1-x0
        phase=((y-yb)%TOOTH)/TOOTH       # 0..1 inside each tooth
        depth=0.40+0.46*(1-abs(phase*2-1)) # triangle wave between .42w and .80w
        right.append((x0+depth*w,y))
    # pointed ends like Gilgongo's strip
    (yb0,(bx0,bx1))=run[0]; (yt0,(tx0,tx1))=run[-1]
    pts=[(tx0+0.5*(tx1-tx0),yt0+26)]+left[::-1]+[(bx0+0.45*(bx1-bx0),yb0-30)]+right
    return pts

def fmt(v): return f'{v:.0f}'

def build(text):
    x=0; glyph_d=[]; cuts=[]
    for ch in text:
        if ch==' ':
            x+=hmtx['space'][0]+TRACK; continue
        gn=cmap[ord(ch)]; adv=hmtx[gn][0]
        rp=DecomposingRecordingPen(gs); gs[gn].draw(rp)
        fp=FlatPen(gs); rp.replay(fp)
        polys=[[(px+x,-py) for px,py in poly] for poly in fp.polys]
        sp=SVGPathPen(gs)
        from fontTools.pens.transformPen import TransformPen
        tp=TransformPen(sp,(1,0,0,-1,x,0)); rp.replay(tp)
        glyph_d.append(sp.getCommands())
        # zigzag computed in flipped coords (y down) -> intervals need y-up; use original then flip
        polys_up=[[(px+x,py) for px,py in poly] for poly in fp.polys]
        z=zigzag(polys_up)
        if z: cuts.append('M'+' L'.join(f'{fmt(a)} {fmt(-b)}' for a,b in z)+'Z')
        x+=adv+TRACK
    width=x-TRACK
    asc=f['hhea'].ascent; desc=f['hhea'].descent
    return {'d':' '.join(glyph_d),'cuts':' '.join(cuts),'width':round(width),'top':-800,'height':1080}

data={'line1':build('From evidence'),'line2':build('to impact')}
js='// Generated by gen/hero_svg.py — Poppins ExtraBold outlines for the hero headline,\n// with a Gilgongo-style zigzag strip cut into the first stroke of each letter.\nexport const heroTitle = '+json.dumps(data)+'\n'
open('src/components/heroTitleData.js','w').write(js)
print({k:(v['width'],v['height'],len(v['d']),len(v['cuts'])) for k,v in data.items()})
